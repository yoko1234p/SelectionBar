import { build } from 'esbuild';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const output = path.resolve(root, '../../Sources/SelectionBarCore/Resources');
await build({
  absWorkingDir: root,
  entryPoints: ['entry.cjs'], outfile: path.join(output, 'vendor-api.js'),
  bundle: true, format: 'iife', platform: 'browser', target: 'safari17',
  minify: true, legalComments: 'linked',
  alias: { path: 'path-browserify', stream: 'stream-browserify', util: 'util' },
  define: { global: 'globalThis', 'process.env.NODE_ENV': '"production"', 'process.env.DEBUG': 'undefined' },
  banner: { js: '/* Generated by Tools/CompatibilityRuntime/build.mjs. See vendor-licenses.txt. */' },
});

// Keep each dependency's notices with the distributed runtime, including transitives.
const notices = [];
async function collect(directory) {
  for (const item of await readdir(directory, { withFileTypes: true })) {
    if (!item.isDirectory() || item.name.startsWith('.')) continue;
    const packageRoot = path.join(directory, item.name);
    if (item.name.startsWith('@')) { await collect(packageRoot); continue; }
    let metadata;
    try { metadata = JSON.parse(await readFile(path.join(packageRoot, 'package.json'), 'utf8')); }
    catch { continue; }
    const licenses = (await readdir(packageRoot)).filter(name => /^(licen[sc]e|copying|notice)([.\-_]|$)/i.test(name));
    for (const name of licenses) {
      try {
        notices.push(`=== ${metadata.name}@${metadata.version} — ${name} ===\n${await readFile(path.join(packageRoot, name), 'utf8')}`);
      } catch { /* A LICENSE directory is not an individual notice file. */ }
    }
    try { await collect(path.join(packageRoot, 'node_modules')); } catch { /* no nested dependencies */ }
  }
}
await collect(path.join(root, 'node_modules'));
await writeFile(path.join(output, 'vendor-licenses.txt'), notices.sort().join('\n\n'));
